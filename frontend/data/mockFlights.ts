export function getMinPrice(flightId: string): number {
  const fares = mockFares[flightId] || [];
  if (fares.length === 0) return 0;
  return Math.min(...fares.map((f) => f.price));
}

export function searchFlights(
  origin: string,
  destination: string,
  date: string
): FlightSearchResult {
  const filteredFlights = mockFlights.filter(
    (flight) =>
      (!origin ||
        flight.origin.toLowerCase().includes(origin.toLowerCase())) &&
      (!destination ||
        flight.destination.toLowerCase().includes(destination.toLowerCase()))
  );

  return {
    flights: filteredFlights,
    fares: mockFares,
    searchParams: {
      origin,
      destination,
      departureDate: date,
      passengers: { adults: 1, children: 0, infants: 0 },
    },
    totalResults: filteredFlights.length,
  };
}

export function getFlightById(id: string): Flight | undefined {
  return mockFlights.find((flight) => flight.id === id);
}

export function getFaresByFlightId(flightId: string): Fare[] {
  return mockFares[flightId] || [];
}
